def _string_to_bytes(rows):
    """Convert an 8-row glyph string into 8 bytes (MSB left)."""
    out = []
    for row in rows:
        byte = 0
        for i, ch in enumerate(row[:GLYPH_W]):
            if ch == '#':
                byte |= 1 << (GLYPH_W - 1 - i)
        out.append(byte)
    return out


def _make_atlas():
    """Build a full 8x6 grid of glyphs as a list of byte rows."""
    atlas_rows = []
    for row in range(ATLAS_ROWS):
        for gy in range(GLYPH_H):
            line = []
            for col in range(ATLAS_COLS):
                code = FIRST_CHAR + row * ATLAS_COLS + col
                glyph = _GLYPHS.get(code)
                if glyph is None:
                    glyph = _GLYPHS[32]  # blank fallback
                byte = _string_to_bytes(glyph)[gy]
                # expand byte to 8 bits
                for bit in range(GLYPH_W - 1, -1, -1):
                    line.append(255 if (byte & (1 << bit)) else 0)
            atlas_rows.append(line)
    return atlas_rows


def _write_png(atlas):
    width = ATLAS_COLS * GLYPH_W
    height = ATLAS_ROWS * GLYPH_H
    img = Image.new('L', (width, height), 0)
    pixels = img.load()
    for y, row in enumerate(atlas):
        for x, val in enumerate(row):
            pixels[x, y] = val
    os.makedirs(os.path.dirname(OUT_PNG), exist_ok=True)
    img.save(OUT_PNG)
    print(f"Wrote font atlas PNG: {OUT_PNG}")


def _write_header(atlas):
    # Build the 1-bit byte array
    bytes_list = []
    for row in atlas:
        # Pack each 8-pixel run into a byte
        for x in range(0, len(row), GLYPH_W):
            byte = 0
            for bit in range(GLYPH_W):
                if row[x + bit]:
                    byte |= 1 << (GLYPH_W - 1 - bit)
            bytes_list.append(byte)

    data_str = ", ".join(f"0x{b:02x}" for b in bytes_list)

    header = f"""#pragma once

// Auto-generated by tools/generate_bitmap_font.py.
// Do not edit manually; regenerate the file instead.

#include <cstdint>

namespace BitmapFontData {{

constexpr int GLYPH_W = {GLYPH_W};
constexpr int GLYPH_H = {GLYPH_H};
constexpr int FIRST_CHAR = {FIRST_CHAR};   // ' '
constexpr int CHAR_COUNT = {CHAR_COUNT};    // ' ' through '~'
constexpr int ATLAS_COLS = {ATLAS_COLS};
constexpr int ATLAS_ROWS = {ATLAS_ROWS};
constexpr int ATLAS_WIDTH = ATLAS_COLS * GLYPH_W;
constexpr int ATLAS_HEIGHT = ATLAS_ROWS * GLYPH_H;

// One bit per pixel; MSB is the leftmost pixel of each 8-pixel row.
// Layout: character code order left-to-right, top-to-bottom.
inline constexpr uint8_t g_fontData[{len(bytes_list)}] = {{
    {data_str}
}};

}} // namespace BitmapFontData
"""
    os.makedirs(os.path.dirname(OUT_HEADER), exist_ok=True)
    with open(OUT_HEADER, 'w') as f:
        f.write(header)
    print(f"Wrote font data header: {OUT_HEADER}")


def main():
    atlas = _make_atlas()
    _write_png(atlas)
    _write_header(atlas)


if __name__ == "__main__":
    main()
